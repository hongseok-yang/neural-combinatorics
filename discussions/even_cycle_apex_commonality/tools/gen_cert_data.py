#!/usr/bin/env python3
"""Generate the certificate schema and data for the Lean checker (encoding of DEVIATIONS X3).

Usage (from the directory even_cycle_apex_commonality):
    python tools/gen_cert_data.py schema          -> lean/EvenCycleApex/Certificate/Schema.lean

Inputs: certificates/lean-data/feature_schema.json (exported by independent_audit.py --export).
The schema is literal data; Lean checks `Schema.ok` and the block dimensions itself.
"""
import json
import sys
from pathlib import Path

EDGES = [(i, j) for i in range(6) for j in range(i + 1, 6)]
INDEX = {e: k for k, e in enumerate(EDGES)}
ROOT = Path(__file__).resolve().parents[1]


def mask(es):
    m = 0
    for i, j in es:
        m |= 1 << INDEX[tuple(sorted((i, j)))]
    return m


def root_pairs(r):
    return [(i, j) for i in range(r) for j in range(i + 1, r)]


def type_mask(r, t):
    """Root type `t` (bit e = e-th root pair in lexicographic order) as a six-vertex mask."""
    return sum(1 << INDEX[e] for b, e in enumerate(root_pairs(r)) if (t >> b) & 1)


def swap_code(r, k):
    sigma = []
    for v in range(6):
        if v < r:
            sigma.append(v)
        elif v < r + k:
            sigma.append(v + k)
        elif v < r + 2 * k:
            sigma.append(v - k)
        else:
            sigma.append(v)
    assert sorted(sigma) == list(range(6))
    return sum(s << (3 * v) for v, s in enumerate(sigma))


def groups():
    """The five groups (blocks with the same number of roots), in block order."""
    blocks = json.loads((ROOT / 'certificates' / 'lean-data' / 'feature_schema.json').read_text())
    out = []
    for b, blk in enumerate(blocks):
        r, k = blk['roots'], blk['new_vertices']
        feats = [mask(f) for f in blk['features']]
        if out and out[-1]['r'] == r:
            assert out[-1]['feats'] == feats and out[-1]['k'] == k
            out[-1]['types'].append(blk['root_type'])
            out[-1]['blocks'].append(b)
        else:
            out.append({'r': r, 'k': k, 'p': 6 - r - 2 * k, 'feats': feats, 'types': [blk['root_type']],
                        'blocks': [b]})
    assert [g['r'] for g in out] == [0, 1, 2, 3, 4]
    for g in out:
        g['sigma'] = swap_code(g['r'], g['k'])
        g['rootMask'] = mask(root_pairs(g['r']))
        g['typeMasks'] = [type_mask(g['r'], t) for t in g['types']]
        g['weight'] = 1 << (6 - len(root_pairs(g['r'])))
    return out


def lean_list(xs):
    return '[' + ', '.join(str(x) for x in xs) + ']'


def gen_schema(path):
    gs = groups()
    s = '''/-!
# The certificate feature schema

Blueprint `def:feature-schema`: the nineteen blocks, grouped by their number of roots `r`
(`schema0`, …, `schema4`; the blocks of a group share their features and differ in the root type).
Every feature is a six-vertex mask on the roots `0, …, r − 1` and the first copy
`r, …, r + k − 1`; root types are six-vertex masks of root pairs (the blueprint's type `t` has bit `e`
for the `e`-th root pair in lexicographic order).  `sigma` is the block swap (roots fixed, first and
second copy exchanged), `weight = 2^{6 − C(r,2)}`.

Generated by `tools/gen_cert_data.py schema` from `certificates/lean-data/feature_schema.json`;
do not edit.  The checks `Schema.ok` and the block dimensions are proved below by `decide`.
-/

import EvenCycleApex.Certificate.Checker

namespace EvenCycleApex

'''
    # the import must come first in a Lean file
    s = 'import EvenCycleApex.Certificate.Checker\n\n' + s.replace('import EvenCycleApex.Certificate.Checker\n\n', '')
    for g in gs:
        s += f'''/-- Blocks {g['blocks'][0]}–{g['blocks'][-1]} (`r = {g['r']}`, `k = {g['k']}`); root types {g['types']}. -/
def schema{g['r']} : Schema where
  r := {g['r']}
  k := {g['k']}
  p := {g['p']}
  sigma := {g['sigma']}
  rootMask := {g['rootMask']}
  feats := {lean_list(g['feats'])}
  types := {lean_list(g['typeMasks'])}
  weight := {g['weight']}

'''
    s += '/-- The five groups, in block order. -/\ndef schemas : List Schema := [' + ', '.join(
        f'schema{g["r"]}' for g in gs) + ']\n\n'
    s += '''theorem schemas_ok : ∀ S ∈ schemas, S.ok = true := by decide

/-- The block dimensions `3, 5, 19, 19, 7 × 4, 15 × 11` (`def:feature-schema`). -/
theorem schema_dims :
    (schemas.flatMap fun S => S.types.map fun _ => S.feats.length)
      = [3, 5, 19, 19, 7, 7, 7, 7, 15, 15, 15, 15, 15, 15, 15, 15, 15, 15, 15] := by decide

end EvenCycleApex
'''
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(s)


if __name__ == '__main__':
    what = sys.argv[1] if len(sys.argv) > 1 else 'schema'
    if what == 'schema':
        gen_schema(ROOT / 'lean' / 'EvenCycleApex' / 'Certificate' / 'Schema.lean')
    else:
        raise SystemExit(f'unknown target {what}')
