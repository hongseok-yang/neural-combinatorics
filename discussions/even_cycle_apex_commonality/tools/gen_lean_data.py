#!/usr/bin/env python3
"""Convert the exported certificate data into literal Lean files (plan D6).

Usage (from the directory even_cycle_apex_commonality, after independent_audit.py --export):
    python tools/gen_lean_data.py certificates lean/EvenCycleApex/Certificate/Data

Inputs:  certificates/{mean_three,negative_majority,positive_majority}_sos.json
         certificates/lean-data/ldl_witnesses.json, certificates/lean-data/normalization_witnesses.json
Outputs: Matrices_{MeanThree,Neg,Pos}.lean   the 19 integer matrices of each target
         LDL_{MeanThree,Neg,Pos}.lean        rational LDLᵀ witnesses: strict lower rows of L and the
                                             diagonal δ, each entry a pair (numerator, denominator)
         Perm.lean                           relabelling witnesses, 32 chunks of 1024 entries
                                             ν(g) + 2^15 · code(π_g), code(π) = Σ π(i)·6^i

`mean_two` is excluded (plan D10, DEVIATIONS X2).  The files import only `Init` and contain
definitions only: nothing here is trusted; the Lean checker validates every entry.
"""
import json
import sys
from pathlib import Path

TARGETS = [('mean_three', 'MeanThree'), ('negative_majority', 'Neg'), ('positive_majority', 'Pos')]
DIMS = [3, 5, 19, 19] + [7] * 4 + [15] * 11
DEN = 90315258984881964711936
CHUNK = 1024


def lean_int(x):
    return str(x) if x >= 0 else f'({x})'


def pair(a, b):
    return f'({a}, {b})'


def header(doc, ns):
    return (f'/-! {doc}\n\nGenerated by `tools/gen_lean_data.py`; do not edit.  Literal data only: '
            'no theorem is claimed here. -/\n\nnamespace {ns}\n\n').replace('{ns}', ns)


def matrices_file(cert, name, short):
    obj = json.loads((cert / f'{name}_sos.json').read_text())
    assert obj['target'] == name and int(obj['denominator']) == DEN and obj['block_dims'] == DIMS
    ns = f'EvenCycleApex.Certificate.Data.{short}'
    s = header(f'Integer matrices of the certificate `{name}` (19 blocks, common denominator 𝒟).', ns)
    for j, A in enumerate(obj['matrices']):
        assert len(A) == DIMS[j] and all(len(r) == DIMS[j] for r in A)
        s += f'def A{j} : List (List Int) :=\n  [' + ',\n   '.join(
            '[' + ', '.join(lean_int(int(x)) for x in r) + ']' for r in A) + ']\n\n'
    s += 'def matrices : List (List (List Int)) :=\n  [' + ', '.join(f'A{j}' for j in range(19)) + ']\n\n'
    s += f'end {ns}\n'
    return s


def ldl_file(cert, name, short):
    obj = json.loads((cert / 'lean-data' / 'ldl_witnesses.json').read_text())
    assert int(obj['denominator']) == DEN
    facts = obj['factorizations_of_integer_numerators'][name]
    ns = f'EvenCycleApex.Certificate.Data.{short}'
    s = header(f'Rational LDLᵀ witnesses for the 19 matrices of `{name}`: for block `j`, `L{{j}}` lists\n'
               'the strictly lower rows of the unit lower triangular factor and `D{j}` the diagonal.', ns)
    for j, f in enumerate(facts):
        n = DIMS[j]
        L, d = f['lower'], f['diagonal']
        assert len(L) == n and len(d) == n
        for i in range(n):
            assert L[i][i] == ['1', '1'] and all(L[i][k] == ['0', '1'] for k in range(i + 1, n))
        s += f'def L{j} : List (List (Int × Nat)) :=\n  [' + ',\n   '.join(
            '[' + ', '.join(pair(lean_int(int(a)), b) for a, b in L[i][:i]) + ']' for i in range(n)) + ']\n\n'
        s += f'def D{j} : List (Int × Nat) :=\n  [' + ',\n   '.join(pair(lean_int(int(a)), b) for a, b in d) + ']\n\n'
    s += 'def lower : List (List (List (Int × Nat))) :=\n  [' + ', '.join(f'L{j}' for j in range(19)) + ']\n\n'
    s += 'def diagonal : List (List (Int × Nat)) :=\n  [' + ', '.join(f'D{j}' for j in range(19)) + ']\n\n'
    s += f'end {ns}\n'
    return s


def perm_file(cert):
    w = json.loads((cert / 'lean-data' / 'normalization_witnesses.json').read_text())
    nf, perms = w['normal_form'], w['permutation']
    assert len(nf) == len(perms) == 1 << 15
    entries = []
    for g in range(1 << 15):
        p = perms[g]
        assert sorted(p) == list(range(6)) and 0 <= nf[g] < 1 << 15
        entries.append(nf[g] + (sum(p[i] * 6 ** i for i in range(6)) << 15))
    ns = 'EvenCycleApex.Certificate.Data.Perm'
    s = header('Relabelling witnesses for all 32,768 six-vertex masks.  Entry `g` of the concatenated\n'
               'chunks is `ν(g) + 2^15 · code(π_g)` with `code(π) = Σᵢ π(i)·6^i`.', ns)
    names = []
    for c in range(0, 1 << 15, CHUNK):
        names.append(f'chunk{c // CHUNK}')
        s += f'def {names[-1]} : List Nat :=\n  [' + ', '.join(map(str, entries[c:c + CHUNK])) + ']\n\n'
    s += 'def chunks : List (List Nat) :=\n  [' + ', '.join(names) + ']\n\n'
    s += f'end {ns}\n'
    return s


def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)


def main():
    cert, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    for name, short in TARGETS:
        write(out / f'Matrices_{short}.lean', matrices_file(cert, name, short))
        write(out / f'LDL_{short}.lean', ldl_file(cert, name, short))
    write(out / 'Perm.lean', perm_file(cert))
    for f in sorted(out.glob('*.lean')):
        print(f'{f.name}: {f.stat().st_size} bytes')


if __name__ == '__main__':
    main()
