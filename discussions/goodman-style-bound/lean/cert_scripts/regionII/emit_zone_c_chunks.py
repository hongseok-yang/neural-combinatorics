#!/usr/bin/env python3
"""Emit the Zone-C certificate as bounded Lean kernel-checking chunks.

The emitter is not trusted: it serializes tree data and small theorem
statements only.  Lean checks every leaf predicate with ``decide +kernel``
and assembles the checked subtrees with ordinary proof terms.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from emit_certificates import Node, zone_c_tree


ROOT = Path(__file__).resolve().parents[2]
OUTPUT_DIR = (
    ROOT / "OddCycleBound" / "RegionII" / "Certificate" / "ZoneCChunks"
)
FINAL_OUTPUT = (
    ROOT / "OddCycleBound" / "RegionII" / "Certificate" / "ZoneCChunked.lean"
)
CHUNK_NODE_LIMIT = 31
CHUNKS_PER_FILE = 16


@dataclass(frozen=True)
class TreeRef:
    tree_name: str
    valid_name: str
    box_expr: str


@dataclass(frozen=True)
class Chunk:
    ref: TreeRef
    node: Node


@dataclass(frozen=True)
class Assembly:
    ref: TreeRef
    split_token: str
    left: TreeRef
    right: TreeRef


def node_sizes(root: Node) -> dict[int, int]:
    sizes: dict[int, int] = {}

    def visit(node: Node) -> int:
        size = 1
        if node.left is not None and node.right is not None:
            size += visit(node.left) + visit(node.right)
        sizes[id(node)] = size
        return size

    visit(root)
    return sizes


def children(node: Node, box_expr: str):
    if node.left is None or node.right is None:
        raise ValueError("leaf has no children")
    if node.token == "splitE":
        split = "RatBox.splitE"
    elif node.token == "splitK":
        split = "RatBox.splitK"
    else:
        raise ValueError(f"unexpected internal token {node.token}")
    pair = f"({split} ({box_expr}))"
    return (node.left, f"{pair}.1"), (node.right, f"{pair}.2")


def token_expr(token: str) -> str:
    if token.startswith("cVerified "):
        return f"(.cVerified {token.split()[1]})"
    return f"(.{token})"


def tree_expr(node: Node, box_expr: str, indent: int = 0) -> str:
    pad = " " * indent
    if node.left is None:
        return f"{pad}(.leaf {box_expr} {token_expr(node.token)})"
    (left, left_box), (right, right_box) = children(node, box_expr)
    ctor = ".splitE" if node.token == "splitE" else ".splitK"
    return (
        f"{pad}({ctor} {box_expr}\n"
        f"{tree_expr(left, left_box, indent + 2)}\n"
        f"{tree_expr(right, right_box, indent + 2)})"
    )


def partition(root: Node):
    sizes = node_sizes(root)
    chunks: list[Chunk] = []
    assemblies: list[Assembly] = []

    def visit(node: Node, box_expr: str) -> TreeRef:
        if sizes[id(node)] <= CHUNK_NODE_LIMIT:
            index = len(chunks)
            ref = TreeRef(
                f"zoneCChunk{index:03d}",
                f"zoneCChunk{index:03d}_valid",
                box_expr,
            )
            chunks.append(Chunk(ref, node))
            return ref

        (left, left_box), (right, right_box) = children(node, box_expr)
        left_ref = visit(left, left_box)
        right_ref = visit(right, right_box)
        index = len(assemblies)
        ref = TreeRef(
            f"zoneCAssembly{index:03d}",
            f"zoneCAssembly{index:03d}_valid",
            box_expr,
        )
        assemblies.append(Assembly(ref, node.token, left_ref, right_ref))
        return ref

    root_ref = visit(root, "zoneCRoot")
    return chunks, assemblies, root_ref


def chunk_module(index: int, chunks: list[Chunk]) -> str:
    lines = [
        "import OddCycleBound.RegionII.Certificate.Coverage",
        "",
        "/-! Deterministically generated by `emit_zone_c_chunks.py`. -/",
        "",
        "namespace OddCycleBound.RegionII.Certificate",
        "",
    ]
    for chunk in chunks:
        lines.extend(
            [
                f"def {chunk.ref.tree_name} : BoxTree :=",
                tree_expr(chunk.node, chunk.ref.box_expr, 2),
                "",
                "set_option maxRecDepth 100000 in",
                "set_option maxHeartbeats 0 in",
                f"theorem {chunk.ref.valid_name} :",
                f"    {chunk.ref.tree_name}.validC {chunk.ref.box_expr} = true := by",
                "  decide +kernel",
                "",
            ]
        )
    lines.extend(["end OddCycleBound.RegionII.Certificate", ""])
    return "\n".join(lines)


def assembly_module(batch_count: int, assemblies: list[Assembly], root: TreeRef) -> str:
    lines = [
        *(f"import OddCycleBound.RegionII.Certificate.ZoneCChunks.Chunk{i:02d}"
          for i in range(batch_count)),
        "",
        "/-! Deterministically generated bounded assembly of the Zone-C tree. -/",
        "",
        "namespace OddCycleBound.RegionII.Certificate",
        "",
    ]
    for assembly in assemblies:
        ctor = ".splitE" if assembly.split_token == "splitE" else ".splitK"
        helper = "BoxTree.validC_splitE" if assembly.split_token == "splitE" else "BoxTree.validC_splitK"
        lines.extend(
            [
                f"def {assembly.ref.tree_name} : BoxTree :=",
                f"  {ctor} {assembly.ref.box_expr}",
                f"    {assembly.left.tree_name} {assembly.right.tree_name}",
                "",
                f"theorem {assembly.ref.valid_name} :",
                f"    {assembly.ref.tree_name}.validC {assembly.ref.box_expr} = true := by",
                f"  unfold {assembly.ref.tree_name}",
                f"  exact {helper} {assembly.left.valid_name} {assembly.right.valid_name}",
                "",
            ]
        )
    lines.extend(
        [
            "def zoneCChunkedTree : BoxTree :=",
            f"  {root.tree_name}",
            "",
            "theorem zoneC_chunkedTree_valid :",
            "    zoneCChunkedTree.validC zoneCRoot = true := by",
            f"  simpa only [zoneCChunkedTree] using {root.valid_name}",
            "",
            "end OddCycleBound.RegionII.Certificate",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    tree, stats = zone_c_tree()
    chunks, assemblies, root = partition(tree)
    batches = [
        chunks[i:i + CHUNKS_PER_FILE]
        for i in range(0, len(chunks), CHUNKS_PER_FILE)
    ]
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    expected = {f"Chunk{i:02d}.lean" for i in range(len(batches))}
    for old in OUTPUT_DIR.glob("Chunk*.lean"):
        if old.name not in expected:
            old.unlink()
    for index, batch in enumerate(batches):
        output = OUTPUT_DIR / f"Chunk{index:02d}.lean"
        output.write_text(chunk_module(index, batch), encoding="utf-8", newline="\n")
    FINAL_OUTPUT.write_text(
        assembly_module(len(batches), assemblies, root),
        encoding="utf-8",
        newline="\n",
    )
    print(
        f"Zone C: {stats}; chunks={len(chunks)}; assemblies={len(assemblies)}; "
        f"modules={len(batches)}; node_limit={CHUNK_NODE_LIMIT}"
    )
    print(f"wrote {OUTPUT_DIR} and {FINAL_OUTPUT}")


if __name__ == "__main__":
    main()
