    ('$K_4$ two-edge-tail', '$K_4$ two-edge tail'),
    ('$C_4$ triangle-page', '$C_4$ page concentration'),
    ('Atlas 148 paw-bias', 'Paw-bias projection (148)'),
    ('Fractional-fibre', 'Fractional-fibre counterexample'),
