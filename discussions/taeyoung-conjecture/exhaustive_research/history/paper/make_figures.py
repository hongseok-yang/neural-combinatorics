"""Generate fig_timeline.tex (Figure 1 of the case-study paper): one lane per participant,
bars at the logged session times (KST). The 27 Aug - 20 Sep gap is compressed to a break.

Run from this directory:  python make_figures.py
"""
import os
from datetime import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
T0 = datetime(2026, 8, 13)
SCALE = 0.75          # cm per day
BREAK_FROM, BREAK_TO, BREAK_W = 14.5, 38.9, 0.9


def day(s):
    return (datetime.strptime(s, '%Y-%m-%d %H:%M') - T0).total_seconds() / 86400


def x(d):
    if d <= BREAK_FROM:
        return SCALE * d
    assert d >= BREAK_TO, d
    return SCALE * BREAK_FROM + BREAK_W + SCALE * (d - BREAK_TO)


LANES = [  # (lane label, colour, [(start, end, label, deleted?)], [(time, marker label)])
    ('Human author', 'black', [], []),
    ('Codex, workstation', 'codex', [
        ('2026-08-13 10:41', '2026-08-13 14:38', '', False),
        ('2026-08-13 14:38', '2026-08-14 14:12', 'goal run 1', False),
        ('2026-08-18 10:32', '2026-08-18 11:47', '', False),
        ('2026-08-18 11:50', '2026-08-19 20:34', 'goal run 2', False),
        ('2026-08-25 13:16', '2026-08-26 20:42', 'formalize SOS', False),
        ('2026-09-21 15:54', '2026-09-22 12:16', '', False),
    ], []),
    ('Claude Code, workstation', 'claude', [
        ('2026-08-13 14:44', '2026-08-14 14:08', 'Lean worker', True),
        ('2026-08-18 10:47', '2026-08-20 07:09', '', True),
        ('2026-09-22 12:20', '2026-09-23 00:03', '', False),
        ('2026-09-23 00:04', '2026-09-23 13:44', '', False),
    ], []),
    ('Codex, second device', 'codex', [
        ('2026-08-22 19:46', '2026-08-22 20:10', '', False),
        ('2026-08-23 21:43', '2026-08-24 02:28', '', False),
        ('2026-08-24 11:55', '2026-08-24 12:03', '', False),
        ('2026-08-25 01:34', '2026-08-25 12:13', '', False),
        ('2026-08-26 03:07', '2026-08-26 11:34', '', False),
    ], []),
    ('ChatGPT Pro (web)', 'chatgpt', [
        ('2026-08-18 11:29', '2026-08-18 12:10', '', False),
        ('2026-08-19 17:12', '2026-08-20 15:11', '', False),
        ('2026-08-20 23:46', '2026-08-23 11:26', 'house thread', False),
        ('2026-08-23 17:07', '2026-08-23 17:52', '', False),
        ('2026-08-23 22:50', '2026-08-24 15:58', '', False),
    ], []),
    ('Co-author pipeline', 'coauthor', [], [('2026-08-20 15:16', '')]),
]
COMMITS = ['2026-08-18 21:11', '2026-08-20 23:40', '2026-08-24 12:02', '2026-08-25 12:12',
           '2026-08-26 17:00', '2026-09-22 12:15', '2026-09-23 13:43']
ANNOT = [  # (lane index, time, text, above?)

    (1, '2026-09-21 23:00', 'compact', True),
    (2, '2026-09-22 18:00', 'audit, last 5', True),
    (3, '2026-08-24 00:05', '6 forks', True),
    (3, '2026-08-25 06:50', '/goal run', False),
    (5, '2026-08-20 15:16', 'deflag note (inferred)', True),
]
TICKS = [('13 Aug', '2026-08-13 00:00'), ('15', '2026-08-15 00:00'), ('17', '2026-08-17 00:00'),
         ('19', '2026-08-19 00:00'), ('21', '2026-08-21 00:00'), ('23', '2026-08-23 00:00'),
         ('25', '2026-08-25 00:00'), ('27', '2026-08-27 00:00'), ('21 Sep', '2026-09-21 00:00'),
         ('23', '2026-09-23 00:00')]

LANE_H = 0.8
out = ['% Generated by make_figures.py; do not edit by hand.',
       '\\begin{tikzpicture}[font=\\scriptsize]']
xmax = x(day('2026-09-23 23:59'))
n = len(LANES)
for i, (label, col, bars, marks) in enumerate(LANES):
    y = -i * LANE_H
    out.append(f'\\node[anchor=east] at (-0.1,{y:.3f}) {{{label}}};')
    out.append(f'\\draw[black!15] (0,{y:.3f}) -- ({xmax:.3f},{y:.3f});')
    for s, e, lab, deleted in bars:
        a, b = x(day(s)), x(day(e))
        b = max(b, a + 0.06)
        style = f'pattern=north east lines, pattern color={col}, draw={col}' if deleted else f'fill={col}, draw={col}'
        out.append(f'\\filldraw[{style}] ({a:.3f},{y - 0.14:.3f}) rectangle ({b:.3f},{y + 0.14:.3f});')
        if lab:
            out.append(f'\\node[above, inner sep=1pt] at ({(a + b) / 2:.3f},{y + 0.14:.3f}) {{{lab}}};')
    for t, lab in marks:
        a = x(day(t))
        out.append(f'\\fill[{col}] ({a:.3f},{y:.3f}) circle (0.09);')
for t in COMMITS:
    a = x(day(t))
    out.append(f'\\draw[fill=white] ({a:.3f},0) circle (0.08);')
out.append(f'\\node[above, inner sep=1pt] at ({x(day("2026-08-18 21:11")):.3f},0.1) {{commits}};')
for li, t, txt, above in ANNOT:
    a = x(day(t))
    y = -li * LANE_H
    if above:
        out.append(f'\\node[above, inner sep=1pt] at ({a:.3f},{y + 0.14:.3f}) {{{txt}}};')
    else:
        out.append(f'\\node[below, inner sep=1pt] at ({a:.3f},{y - 0.14:.3f}) {{{txt}}};')
# the author's absence and the axis break
bx0, bx1 = SCALE * BREAK_FROM, SCALE * BREAK_FROM + BREAK_W
ybot = -(n - 1) * LANE_H - 0.45
out.append(f'\\fill[white] ({bx0 + 0.08:.3f},{ybot:.3f}) rectangle ({bx1 - 0.08:.3f},0.45);')
out.append(f'\\node[align=center, text width=0.9cm, font=\\tiny] at ({(bx0 + bx1) / 2:.3f},{-(n - 1) * LANE_H / 2:.3f}) '
           '{author away 27\\,Aug--20\\,Sep};')
out.append(f'\\draw ({0:.3f},{ybot:.3f}) -- ({bx0 + 0.05:.3f},{ybot:.3f});')
out.append(f'\\draw ({bx1 - 0.05:.3f},{ybot:.3f}) -- ({xmax:.3f},{ybot:.3f});')
out.append(f'\\draw ({bx0 - 0.03:.3f},{ybot - 0.1:.3f}) -- ({bx0 + 0.11:.3f},{ybot + 0.1:.3f});')
out.append(f'\\draw ({bx1 - 0.11:.3f},{ybot - 0.1:.3f}) -- ({bx1 + 0.03:.3f},{ybot + 0.1:.3f});')
for lab, t in TICKS:
    a = x(day(t))
    out.append(f'\\draw ({a:.3f},{ybot:.3f}) -- ({a:.3f},{ybot - 0.08:.3f}) node[below] {{{lab}}};')
out.append('\\end{tikzpicture}')
open(os.path.join(HERE, 'fig_timeline.tex'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('width (cm):', round(xmax, 2))
